import { test, expect } from '@playwright/test';

test('admin schedules a 3D lesson for a week, edits a day and cancels without deleting it',async({page,browser})=>{
  await page.goto('/admin/login');
  await page.getByLabel('Почта',{exact:true}).fill('admin@aiteacher.local');
  await page.getByLabel('Пароль',{exact:true}).fill('PepeOnly-admin-2026!');
  await page.getByRole('button',{name:'Войти',exact:true}).click();
  await expect(page).toHaveURL(/\/admin$/);
  const boot=await (await page.request.get('/api/auth/me')).json();
  const institutionId=boot.user.institutionId;
  const catalog=await (await page.request.get(`/api/lesson-catalog?institutionId=${institutionId}`)).json();
  const lesson=catalog.find((item:any)=>item.cinemaId==='derivative'&&item.status==='ready');
  expect(lesson).toBeTruthy();
  await page.getByRole('link',{name:'Расписание',exact:true}).first().click();
  await page.getByRole('button',{name:'3D-уроки',exact:true}).click();
  await expect(page.getByRole('heading',{name:lesson.title,exact:true})).toBeVisible();
  await page.screenshot({path:'../AI-Teacher-catalog.png',fullPage:true});
  await page.getByRole('button',{name:'По дням',exact:true}).click();
  await page.getByRole('button',{name:'Добавить занятие',exact:true}).first().click();
  const dialog=page.getByRole('dialog');
  await dialog.getByLabel('Урок расписания',{exact:true}).selectOption(lesson.id);
  await dialog.getByRole('button',{name:'Неделя',exact:true}).click();
  await dialog.getByLabel('Начало периода',{exact:true}).fill('2035-03-05');
  await expect(dialog.getByLabel('Конец периода',{exact:true})).toHaveValue('2035-03-11');
  await dialog.getByLabel('Доступ 24 часа',{exact:true}).check();
  const createdResponse=page.waitForResponse(response=>response.url().endsWith('/api/schedule/events')&&response.request().method()==='POST');
  await dialog.getByRole('button',{name:'Сохранить занятие',exact:true}).click();
  const created=await (await createdResponse).json();
  expect(created.created).toHaveLength(7);
  await expect(dialog).toBeHidden();
  await expect(page.getByLabel('Дата расписания',{exact:true})).toHaveValue('2035-03-05');
  const eventRow=page.locator('[data-schedule-event-id]').filter({hasText:lesson.title});
  await expect(eventRow).toContainText('24 часа');
  await page.screenshot({path:'../AI-Teacher-schedule.png',fullPage:true});
  await eventRow.click();
  await dialog.getByRole('button',{name:'Изменить занятие',exact:true}).click();
  await dialog.getByLabel('Доступ 24 часа',{exact:true}).uncheck();
  await dialog.getByLabel('Время занятия',{exact:true}).fill('10:30');
  await dialog.getByLabel('Длительность занятия',{exact:true}).fill('45');
  await dialog.getByRole('button',{name:'Сохранить занятие',exact:true}).click();
  await expect(dialog).toBeHidden();
  await expect(eventRow).toContainText('10:30');
  await expect(eventRow).toContainText('11:15');
  const teacherContext=await browser.newContext({baseURL:new URL(page.url()).origin});
  const teacher=await teacherContext.newPage();
  await teacher.goto('/login');
  await teacher.getByLabel('Почта',{exact:true}).fill('demo@aiteacher.local');
  await teacher.getByLabel('Пароль',{exact:true}).fill('PepeOnly-teacher-2026!');
  await teacher.getByRole('button',{name:'Войти',exact:true}).click();
  await expect(teacher).toHaveURL(/\/teach$/);
  const teacherData=await (await teacher.request.get(`/api/university?institutionId=${institutionId}&date=2035-03-06`)).json();
  expect(teacherData.events.some((item:any)=>item.lessonId===created.created[1].lessonId&&item.allDay===true)).toBe(true);
  await eventRow.click();
  await dialog.getByRole('button',{name:'Отменить занятие',exact:true}).click();
  await expect(dialog.getByText('Посещаемость и история занятия сохранятся.')).toBeVisible();
  await dialog.getByRole('button',{name:'Отменить занятие',exact:true}).click();
  await expect(dialog).toBeHidden();
  await expect(eventRow).toHaveCount(0);
  const records=await (await page.request.get(`/api/schedule/events?institutionId=${institutionId}&from=2035-03-05&to=2035-03-11&includeCancelled=true`)).json();
  expect(records).toHaveLength(7);
  expect(records.filter((item:any)=>item.cancelled)).toHaveLength(1);
  expect(records.filter((item:any)=>!item.cancelled&&item.allDay)).toHaveLength(6);
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
  await page.getByRole('button',{name:'3D-уроки',exact:true}).click();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
  await teacherContext.close();
});
