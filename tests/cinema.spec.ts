import {test,expect} from '@playwright/test';
test('cinematic lesson plays local voice, pauses, seeks, restores position and stays usable on mobile',async({page})=>{
 test.setTimeout(60_000);
 const errors:string[]=[],external:string[]=[];
 page.on('pageerror',error=>errors.push(error.message));
 page.on('request',request=>{if(/^https?:/.test(request.url())&&!request.url().startsWith('http://127.0.0.1:3101'))external.push(request.url());});
 await page.addInitScript(()=>{(window as any).__cameraAttempts=0;Object.defineProperty(navigator.mediaDevices,'getUserMedia',{configurable:true,value:async()=>{(window as any).__cameraAttempts++;throw new Error('Preview must not open camera');}});});
 await page.goto('/login');
 await page.getByLabel('Почта',{exact:true}).fill('demo@aiteacher.local');
 await page.getByLabel('Пароль',{exact:true}).fill('PepeOnly-teacher-2026!');
 await page.getByRole('button',{name:'Войти',exact:true}).click();
 await expect(page).toHaveURL(/\/teach$/);
 await page.goto('/teach?preview=derivative');
 const stage=page.getByRole('region',{name:'Урок: Производная'});
 await expect(stage).toBeVisible();
 await expect(page.locator('.derivative-scene')).toHaveAttribute('data-renderer','webgl');
 const timeline=page.getByRole('slider',{name:'Позиция урока'});
 const manifest=await (await page.request.get('/api/cinema/derivative')).json();
 expect(manifest.id).toBe('derivative-cinema-v3');
 expect(manifest.voice.status).toBe('ready');
 await stage.hover();
 const play=page.getByRole('button',{name:'Продолжить урок',exact:true});
 if(await play.isVisible())await play.click();
 await expect.poll(async()=>Number(await timeline.inputValue())).toBeGreaterThan(.5);
 await stage.hover();
 await page.getByRole('button',{name:'Пауза',exact:true}).click();
 const paused=Number(await timeline.inputValue());
 await page.waitForTimeout(400);
 expect(Math.abs(Number(await timeline.inputValue())-paused)).toBeLessThan(.12);
 const limit=manifest.chapters.find((chapter:any)=>chapter.scene==='limit');
 const box=await timeline.boundingBox();
 await page.mouse.click(box!.x+box!.width*(limit.start+limit.beats[3].at+2)/manifest.duration,box!.y+box!.height/2);
 await expect(stage).toHaveAttribute('data-scene','limit');
 await expect(page.locator('.math-lim')).toBeVisible();
 const sought=Number(await timeline.inputValue());
 expect(sought).toBeGreaterThan(limit.start);
 await page.getByRole('button',{name:'Продолжить',exact:true}).click();
 await page.mouse.move(10,10);
 await expect(page.locator('.film-controls')).toHaveCSS('opacity','0',{timeout:7000});
 await page.screenshot({path:'../Derivative-Lesson.png'});
 await page.reload();
 await expect(timeline).toBeAttached();
 await expect.poll(async()=>Number(await timeline.inputValue())).toBeGreaterThan(sought-1);
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
 await expect(stage).toBeVisible();
 expect(await page.evaluate(()=>(window as any).__cameraAttempts)).toBe(0);
 await page.keyboard.press('Tab');
 await page.getByRole('button',{name:'Закрыть урок',exact:true}).click();
 await expect(page).toHaveURL(/\/teach$/);
 expect(errors).toEqual([]);
 expect(external).toEqual([]);
});
